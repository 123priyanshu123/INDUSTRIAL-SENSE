export const GENERATE_SERIES_DATA = (points = 30) => {
  const data = [];
  const now = Date.now();
  for (let i = points; i >= 0; i--) {
    const time = new Date(now - i * 60 * 1000).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
    data.push({
      time,
      sound: Math.round(62 + Math.sin(i / 3) * 8 + (Math.random() * 4)),
      temperature: Number((48 + Math.cos(i / 4) * 6 + (Math.random() * 2)).toFixed(1)),
      pressure: Number((4.2 + Math.sin(i / 5) * 0.6 + (Math.random() * 0.2)).toFixed(2)),
      healthIndex: Math.round(88 - (i > 10 ? 2 : 0) + (Math.random() * 3)),
    });
  }
  return data;
};
